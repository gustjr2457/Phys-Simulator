/* 마이컬슨-몰리 실험 — 시뮬레이션 값을 교과서 공식으로 따로 비교한다 (시뮬레이션 코드를 쓰지 않는다).
   에테르 가설 (지구 속도 v, 빛의 속력 c = 299,792,458 m/s):
     바람과 나란한 팔 왕복: 갈 때 L/(c − v), 올 때 L/(c + v) → t∥ = 2Lc/(c² − v²)
     가로지르는 팔 왕복: 빛이 비스듬히 가야 해서 한쪽 L/√(c² − v²) → t⊥ = 2L/√(c² − v²)
     장치를 90° 돌리면 두 팔이 역할을 바꾸므로 무늬 이동 ΔN = 2·c·(t∥ − t⊥)/λ ≈ 2Lv²/(λc²)
   1887년 값 L = 11 m, v = 30 km/s, λ = 550 nm → 약 0.40개 (마이컬슨-몰리 논문의 예측 0.4개).
   돌린 각도 θ 에서 처음 자리 기준 이동은 (ΔN/2)(1 − cos 2θ) (θ = 90° 에서 ΔN). 장치는 15°/s 로 돈다. */
