/* 자이로와 가속도계 합치기 (상보 필터) — 시뮬레이션 값을 교과서 공식으로 따로 비교한다 (시뮬레이션 코드를 쓰지 않는다).
   자이로 치우침 b 를 적분하면 오차는 시간에 비례: e_g(t) = b·t
   1차 상보 필터 de/dt = b − e/τ 의 해: e(t) = b·τ·(1 − e^(−t/τ))  → 정상 상태 b·τ
   0.01 s 마다 갱신하는 이산 필터는 α = τ/(τ + Δt), 과도 응답 b·τ·(1 − α^n) (n = t/Δt)
   백색 잡음(표준편차 σ)이 1차 저역 필터 y ← α·y + (1 − α)·x 를 지나면 분산 σ²·(1 − α)/(1 + α) = σ²·Δt/(2τ + Δt)
   치우침·잡음이 없으면 필터 오차는 처음 0 에서 계속 0. */
