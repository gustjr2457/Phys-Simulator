/* 피토관과 대기속도계 — 시뮬레이션 값을 교과서 공식으로 따로 비교한다 (시뮬레이션 코드를 쓰지 않는다).
   비압축 베르누이: 코끝에서 공기가 멈추면 p₀ = p + ½ρV²  →  Δp = ½ρV²
   계기(해면 밀도 ρ₀ = 1.225 로 눈금): V_i = √(2Δp/ρ₀) = V·√(ρ/ρ₀)
   마노미터: Δp = ρ_물·g·d
   공기 밀도는 국제 표준 대기를 보편 기체상수 R* = 8.314462618 J/(mol·K), 몰질량 M = 0.0289644 kg/mol 로 따로 계산한다.
   알려진 표 값(지오퍼텐셜 고도): ISA 밀도 5 km 0.7364, 11 km 0.3639, 12 km 0.3108 kg/m³ */
const g = 9.80665, Rs = 8.314462618 / .0289644, rho0 = 1.225;
function rhoISA(h) {
  const L = .0065, T0 = 288.15, p0 = 101325;
  if (h <= 11000) { const T = T0 - L * h; return p0 * Math.pow(T / T0, g / (Rs * L)) / (Rs * T); }
  const T11 = T0 - L * 11000, p11 = p0 * Math.pow(T11 / T0, g / (Rs * L));
  return p11 * Math.exp(-g * (h - 11000) / (Rs * T11)) / (Rs * T11);
}

